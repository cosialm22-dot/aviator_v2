#!/usr/bin/env python3
"""Generate src/brand/settings.generated.ts from the database's brand_setting_defs.

The database is the single source of truth for brand settings (key, type, default, visibility).
The web app only needs the PUBLIC keys, typed, with their defaults as an offline fallback until the
live brand arrives. Run after changing brand_setting_defs; `--check` fails if the file is stale
(used by supabase/tests/brand_config_e2e.py so the two can never drift).

  SUPABASE_ACCESS_TOKEN=… SUPABASE_REF=… python3 scripts/sync_brand_settings.py [--check]
"""
import json, os, sys, urllib.request

TOKEN, REF = os.environ["SUPABASE_ACCESS_TOKEN"], os.environ["SUPABASE_REF"]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "brand", "settings.generated.ts")

def sql(q):
    req = urllib.request.Request(f"https://api.supabase.com/v1/projects/{REF}/database/query",
                                 data=json.dumps({"query": q}).encode(), method="POST",
                                 headers={"Authorization": f"Bearer {TOKEN}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode())

rows = sql("select key, kind, default_value, options from brand_setting_defs where is_public order by section, sort, key")
fonts = sql("select public._brand_fonts() f")[0]["f"]
TS = {"bool": "boolean", "int": "number", "number": "number", "money": "number", "list": "number[]"}
def ts_type(r):
    if r["kind"] == "enum":
        return " | ".join(json.dumps(o[0]) for o in r["options"])
    return TS.get(r["kind"], "string")

lines = [
    "// GENERATED by scripts/sync_brand_settings.py from public.brand_setting_defs — do not edit by hand.",
    "// The database is the source of truth; this file types the PUBLIC brand settings and carries their",
    "// defaults as the offline fallback until the live brand arrives.",
    "",
    "export interface BrandSettings {",
]
for r in rows:
    nullable = r["default_value"] is None
    lines.append(f"  {json.dumps(r['key'])}: {ts_type(r)}{' | null' if nullable else ''};")
lines += ["}", "", "export const BRAND_SETTING_DEFAULTS: BrandSettings = {"]
for r in rows:
    lines.append(f"  {json.dumps(r['key'])}: {json.dumps(r['default_value'])},")
lines += ["};", "", "/** Allowed values of every choice setting (the server refuses anything else). */",
          "export const BRAND_SETTING_OPTIONS: Partial<Record<keyof BrandSettings, readonly string[]>> = {"]
for r in rows:
    if r["kind"] == "enum":
        lines.append(f"  {json.dumps(r['key'])}: {json.dumps([o[0] for o in r['options']])},")
lines += ["};", "", "/** Fonts the server accepts in theme tokens (public._brand_fonts()). */",
          f"export const SERVER_FONTS: readonly string[] = {json.dumps(fonts)};", ""]
text = "\n".join(lines)

if "--check" in sys.argv:
    cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if cur != text:
        print("settings.generated.ts is stale — run scripts/sync_brand_settings.py"); sys.exit(1)
    print(f"settings.generated.ts up to date ({len(rows)} public settings)"); sys.exit(0)
open(OUT, "w", encoding="utf-8").write(text)
print(f"wrote {OUT} ({len(rows)} public settings)")
